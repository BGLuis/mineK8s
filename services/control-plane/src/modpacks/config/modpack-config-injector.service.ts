import * as fs from 'node:fs';
import * as path from 'node:path';
import { Injectable, Logger } from '@nestjs/common';
import { Server } from '@database/entities/server.entity';

export interface ConfigInjectionOptions {
  rconPassword?: string;
  isModpack?: boolean;
  serverType?: string;
}

@Injectable()
export class ModpackConfigInjectorService {
  private readonly logger = new Logger(ModpackConfigInjectorService.name);

  /**
   * Injeta determinística e obrigatoriamente a matriz de configurações críticas (RF-STO-14, C-08, C-15).
   *
   * @param serverDataDir Diretório /data da instância.
   * @param options Opções incluindo senha RCON e flags.
   */
  public async injectConfigurationMatrix(
    serverDataDir: string,
    options: ConfigInjectionOptions = {},
  ): Promise<void> {
    await fs.promises.mkdir(serverDataDir, { recursive: true });

    // 1. Injeção mandatória de eula.txt (RF-STO-14)
    await this.injectEula(serverDataDir);

    // 2. Injeção e merge de server.properties (RF-STO-14, C-08, C-15)
    await this.injectServerProperties(serverDataDir, options);

    // 3. Injeção de paper-global.yml para compatibilidade de proxy Gateway L7 (RF-STO-14)
    const isPaperLike =
      options.serverType &&
      ['PAPER', 'PURPUR'].includes(options.serverType.toUpperCase());
    if (isPaperLike) {
      await this.injectPaperGlobal(serverDataDir);
    }

    this.logger.log(`[RF-STO-14] Matriz de configuração injetada com sucesso em ${serverDataDir}`);
  }

  private async injectEula(serverDataDir: string): Promise<void> {
    const eulaPath = path.join(serverDataDir, 'eula.txt');
    await fs.promises.writeFile(eulaPath, '# Generated by MineKubernetes Hypervisor\neula=true\n');
  }

  private async injectServerProperties(
    serverDataDir: string,
    options: ConfigInjectionOptions,
  ): Promise<void> {
    const propsPath = path.join(serverDataDir, 'server.properties');
    const existingProps = new Map<string, string>();

    if (fs.existsSync(propsPath)) {
      const content = await fs.promises.readFile(propsPath, 'utf-8');
      for (const line of content.split('\n')) {
        const trimmed = line.trim();
        if (trimmed && !trimmed.startsWith('#') && trimmed.includes('=')) {
          const idx = trimmed.indexOf('=');
          const key = trimmed.slice(0, idx).trim();
          const val = trimmed.slice(idx + 1).trim();
          existingProps.set(key, val);
        }
      }
    }

    // Regras Mandatórias da Matriz RF-STO-14
    existingProps.set('server-port', '25565');
    existingProps.set('enable-rcon', 'true');
    existingProps.set('rcon.port', '25575');
    if (options.rconPassword) {
      existingProps.set('rcon.password', options.rconPassword);
    } else if (!existingProps.has('rcon.password')) {
      existingProps.set('rcon.password', 'minek8s-rcon-secret');
    }
    existingProps.set('online-mode', 'false');
    existingProps.set('enforce-secure-chat', 'false');

    // Resolução C-08: max-tick-time=-1 para modpacks, 60000 para vanilla
    const isModpack = options.isModpack !== false;
    existingProps.set('max-tick-time', isModpack ? '-1' : '60000');

    // Serializa de volta preservando chave=valor
    const lines = ['# Minecraft server properties - Managed by MineKubernetes'];
    for (const [key, value] of existingProps.entries()) {
      lines.push(`${key}=${value}`);
    }

    await fs.promises.writeFile(propsPath, `${lines.join('\n')}\n`);
  }

  private async injectPaperGlobal(serverDataDir: string): Promise<void> {
    const configDir = path.join(serverDataDir, 'config');
    await fs.promises.mkdir(configDir, { recursive: true });
    const paperGlobalPath = path.join(configDir, 'paper-global.yml');

    const content = `# MineKubernetes Gateway L7 Proxy Compatibility
proxies:
  bungee-cord:
    online-mode: false
  velocity:
    enabled: false
    online-mode: false
    secret: ''
`;
    await fs.promises.writeFile(paperGlobalPath, content);
  }
}
